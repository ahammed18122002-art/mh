const $ = id => document.getElementById(id);
const safe = s => String(s ?? '').replace(/[&<>"']/g, c => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
}[c]));

function safeHref(url) {
  const u = String(url ?? '').trim();
  if (!u) return '#';
  if (/^(https?:\/\/|mailto:|tel:|#|\.?\/?[a-zA-Z0-9_\-./]+\.html)/i.test(u)) {
    return safe(u);
  }
  return '#';
}

function saveLocalMaster(data) {
  try {
    localStorage.setItem(MASTER_STORAGE_KEY, JSON.stringify(data));
  } catch (e) {}
}

function getLocalMaster() {
  try {
    const raw = localStorage.getItem(MASTER_STORAGE_KEY);
    if (!raw) return null;
    const parsed = JSON.parse(raw);
    return parsed && typeof parsed === 'object' ? parsed : null;
  } catch (e) {
    return null;
  }
}

function normalizeMaster(raw) {
  const base = JSON.parse(JSON.stringify(FALLBACK_MASTER));
  if (!raw || typeof raw !== 'object') return base;
  return {
    settings: { ...base.settings, ...(raw.settings || {}) },
    profile: { ...base.profile, ...(raw.profile || {}) },
    about: {
      ...base.about,
      ...(raw.about || {}),
      highlights: Array.isArray(raw.about?.highlights) ? raw.about.highlights : base.about.highlights
    },
    skills: Array.isArray(raw.skills) ? raw.skills : base.skills,
    contact: { ...base.contact, ...(raw.contact || {}) },
    socialLinks: Array.isArray(raw.socialLinks) ? raw.socialLinks : base.socialLinks,
    posts: Array.isArray(raw.posts) ? raw.posts : base.posts,
    serviceCategories: Array.isArray(raw.serviceCategories) && raw.serviceCategories.length
      ? raw.serviceCategories
      : [...new Set([...(base.serviceCategories || []), ...((Array.isArray(raw.services) ? raw.services : base.services).map(s => s.category).filter(Boolean))])],
    services: Array.isArray(raw.services) ? raw.services : base.services,
    certificates: Array.isArray(raw.certificates) ? raw.certificates : base.certificates,
    photos: Array.isArray(raw.photos) ? raw.photos : base.photos,
    agency: {
      ...base.agency,
      ...(raw.agency || {}),
      whyChoose: Array.isArray(raw.agency?.whyChoose) ? raw.agency.whyChoose : base.agency.whyChoose,
      process: Array.isArray(raw.agency?.process) ? raw.agency.process : base.agency.process,
      highlights: Array.isArray(raw.agency?.highlights) ? raw.agency.highlights : base.agency.highlights
    }
  };
}

async function loadMasterData(preferLocalForAdmin = false) {
  const local = getLocalMaster();
  if (preferLocalForAdmin && local) {
    return normalizeMaster(local);
  }
  if (window.location.protocol !== 'file:') {
    try {
      const res = await fetch(`master.json?t=${Date.now()}`, { cache: 'no-store' });
      if (res.ok) {
        const data = await res.json();
        const normalized = normalizeMaster(data);
        if (!preferLocalForAdmin) {
          saveLocalMaster(normalized);
        }
        return normalized;
      }
    } catch (e) {}
  }
  if (local) return normalizeMaster(local);
  const fallback = normalizeMaster(FALLBACK_MASTER);
  saveLocalMaster(fallback);
  return fallback;
}

/* =========================================================
   1. THEME SYSTEM (Device Preference + Manual Toggle)
   ========================================================= */
function initTheme() {
  const toggleBtn = $('themeToggle');
  const iconWrap = $('themeIconWrap');
  const media = window.matchMedia('(prefers-color-scheme: dark)');

  function applyUI(theme) {
    document.documentElement.setAttribute('data-theme', theme);
    if (iconWrap) {
      iconWrap.innerHTML = theme === 'dark'
        ? '<i class="fa-solid fa-moon"></i>'
        : '<i class="fa-solid fa-sun"></i>';
    }
  }

  let saved = null;
  try { saved = localStorage.getItem('theme'); } catch (e) {}
  const initialTheme = saved || (media.matches ? 'dark' : 'light');
  applyUI(initialTheme);

  if (toggleBtn) {
    toggleBtn.addEventListener('click', () => {
      const current = document.documentElement.getAttribute('data-theme');
      const next = current === 'dark' ? 'light' : 'dark';
      try { localStorage.setItem('theme', next); } catch (e) {}
      applyUI(next);
    });
  }

  media.addEventListener('change', e => {
    let manual = null;
    try { manual = localStorage.getItem('theme'); } catch (err) {}
    if (!manual) {
      applyUI(e.matches ? 'dark' : 'light');
    }
  });
}

